package com.aphs.classroomuprising;

/**
 * The periods of a school day, declared in the order they happen (IPO 7).
 *
 * @author TeamPike
 * @since 1.0
 */
public enum DayPeriod {
    /** ICS class, which is also when scheduled Labs and Tests happen. */
    ICS_CLASS,
    /** Other classes. */
    OTHER_CLASSES,
    /** The Student Hub, at the end of the day. */
    STUDENT_HUB
}
